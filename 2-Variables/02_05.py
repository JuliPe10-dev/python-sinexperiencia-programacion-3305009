'''
  Ejemplo de conversiones entre tipos de datos
  y como convertir entre texto, entero y float.
'''
# Ejemplo de texto a entero
numero_texto = "38"
numero_entero = int(numero_texto)
print(numero_entero)
print(type(numero_entero))

# Ejemplo de float a entero
numero_float= 0.5
numero_entero = int(numero_float)
print(numero_entero)
print(type(numero_entero))

# Ejemplo de texto a float
float_texto = "2.5"
numero_float = float(float_texto)
print(numero_float) 
print(type(numero_float))

# Ejemplo de entero a texto
numero_entero = 32
texto_entero = str(numero_entero)
print(texto_entero)
print(type(texto_entero))

# Ejemplo de float a texto
numero_float = 3.14
texto_float = str(numero_float)
print(texto_float)
print(type(texto_float))


