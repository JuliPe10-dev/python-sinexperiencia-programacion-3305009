'''
  Ejemplo de variables de texto con diferentes tipos de comillas
  y como se puede usar comillas dentro de comillas que son diferentes
  a los que delimitan el texto y lo que es dentro del texto.
'''
saludo = "¡Hola, mundo!"
letra = 'a'

print(saludo)
print(letra)

texto_comillas_simples = 'Esto puede ser un saludo:"¡Hola, mundo!"'
texto_comillas_dobles = "Esto puede ser un saludo:'¡Hola, mundo!'"

print(texto_comillas_simples)
print(texto_comillas_dobles)
