'''
    Estructura de control Else es el "sino" de una condición.
    Se utiliza para ejecutar un bloque de código cuando la condición del if es falsa.
    Se puede leer como "si A no es cierto, entonces haz esto".
    En Python, se utiliza la palabra clave 'else' para iniciar una declaración alternativa.
'''

numero = int(input("Ingresar un número: "))

if numero > 0:
    print("El número es positivo")
else:
    print("El número no es positivo")
